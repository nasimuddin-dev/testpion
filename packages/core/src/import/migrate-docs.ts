import { BRU_TO_TP, INSOMNIA_MISSING, POSTMAN_LEGACY_CALLS, POSTMAN_MISSING, POSTMAN_MISSING_HINT } from '../scripts/convert/coverage.js';
import { BRU_CALLS, BRU_REQ_RES, HOPPSCOTCH_RULES, MATCHERS, THUNDER_RULES } from '../scripts/convert/rules.js';
import { IMPORTER_SUPPORT, MATRIX_FEATURES, type ImporterSupport } from './support.js';
import { POSTMAN_WORDS } from '@testpion/shared';

/**
 * The migration guides, generated: one page per source tool (docs/migrate/<id>.md) and an overview with the capability
 * matrix, from the importers' declared support table (support.ts) and the script converter's tables (scripts/convert).
 * `npm run docs:migrate` writes them; tests/unit/migrate-docs.test.ts fails when a page on disk differs from what is
 * generated here, when an importer has no page, or when a format the importer detects is in no table, so the docs
 * cannot drift from the code.
 */

export interface MigratePage {
  /** Relative to docs/, e.g. `migrate/postman.md`. */
  path: string;
  markdown: string;
}

const NOTICE = '<!-- Generated by `npm run docs:migrate` from the importers\' support table (packages/core/src/import/support.ts) and the script converter\'s tables. Do not edit by hand. -->';
const bullets = (l: string[]) => l.map((x) => `- ${x}`).join('\n');
const cell = (s: string) => s.replace(/\|/g, '\\|');

/** A converter rule as a table row: the call as it is written in the source tool, and what it becomes. */
function ruleRow(key: string, rule: unknown): [string, string] {
  const r = rule as { call?: (a: string[], raw: never[]) => string; to?: string; missing?: boolean; lift?: string };
  if (r.call) {
    // the arguments the rule uses: a[0], a[1] … or all of them (a.join)
    const src = r.call.toString();
    if (/a\.join/.test(src)) return [`\`${key}(…)\``, `\`${r.call(['…'], []).replace(/\s+/g, ' ')}\``];
    const used = [...src.matchAll(/a\[(\d)\]/g)].map((m) => Number(m[1]));
    const names = ['a', 'b', 'c'];
    const args = names.slice(0, used.length ? Math.max(...used) + 1 : 0);
    return [`\`${key}(${args.join(', ')})\``, `\`${r.call(names, []).replace(/\s+/g, ' ')}\``];
  }
  if (r.to) return [`\`${key}\``, `\`${r.to.replace(/\s+/g, ' ')}\``];
  if (r.lift) return [`\`${key}(value)\``, `the request's ${r.lift === 'timeoutMs' ? 'timeout' : 'maximum redirects'} setting (a constant), else a \`TODO(import)\``];
  return [`\`${key}\``, 'no equivalent: a `TODO(import)` line and a finding'];
}
const table = (rows: Array<[string, string]>, head: [string, string] = ['In the script', 'Becomes']) => [`| ${head[0]} | ${head[1]} |`, '|---|---|', ...rows.map(([a, b]) => `| ${cell(a)} | ${cell(b)} |`)].join('\n');

/** The script mapping tables of a tool, from the converter's own tables. */
export function scriptTable(t: NonNullable<ImporterSupport['scripts']>['table']): string {
  switch (t) {
    case 'postman':
      return [
        table([
          ['`pm.*`', '`tp.*` (the same API; `pm` keeps working as an alias)'],
          ...Object.entries(POSTMAN_LEGACY_CALLS).map(([k, v]): [string, string] => [`\`postman.${k}\``, `\`${v}\``]),
          ['`tests["name"] = expr`', '`tp.test("name", …)`'],
          ['`responseBody`, `responseCode.code`, `responseTime`, `JSON.parse(responseBody)`', '`tp.response.text()`, `tp.response.code`, `tp.response.responseTime`, `tp.response.json()`'],
          ['`pm.state`', '`tp.state` (kept as globals named `state.<key>`, on this computer)'],
          ...POSTMAN_MISSING.map((m): [string, string] => [`\`pm.${m}\``, `no equivalent (\`TODO(import)\`): ${POSTMAN_MISSING_HINT[m]}`]),
        ]),
      ].join('\n');
    case 'insomnia':
      return table([
        ['`insomnia.*`', '`tp.*` (the same API)'],
        ['`insomnia.baseEnvironment`, `insomnia.collectionVariables`', '`tp.environment` (the base environment is merged into each environment)'],
        ...INSOMNIA_MISSING.map((m): [string, string] => [`\`insomnia.${m}\``, 'no equivalent: a `TODO(import)` line and a finding']),
      ]);
    case 'bruno':
      return [
        table([
          ...Object.entries(BRU_TO_TP).map(([k, v]): [string, string] => [`\`bru.${k.replace(/\(\)$/, '')}${k.endsWith('()') ? '()' : ''}\``, `\`${v}\``]),
          ...Object.entries(BRU_CALLS).map(([k, v]) => ruleRow(k, v)),
          ...Object.entries(BRU_REQ_RES).map(([k, v]) => ruleRow(k, v)),
          ['`test(…)`, `expect(…)`', '`tp.test(…)`, `tp.expect(…)`'],
        ]),
      ].join('\n');
    case 'thunder':
      return table([...Object.entries(THUNDER_RULES).map(([k, v]) => ruleRow(k, v)), ['`expect(…)`', '`tp.expect(…)`']]);
    case 'hoppscotch':
      return [
        table([...Object.entries(HOPPSCOTCH_RULES).map(([k, v]) => ruleRow(k, v)), ['`pm.*`', '`tp.*` (Hoppscotch\'s Postman layer)']]),
        '',
        'Jest-style matchers after `pw.expect(x)` / `hopp.expect(x)` become chai:',
        '',
        table(Object.entries(MATCHERS).map(([k, v]): [string, string] => [`.${k}(…)`, `\`.${v}${/\)$/.test(v) ? '' : '(…)'}\``]), ['Matcher', 'Becomes']),
      ].join('\n');
  }
}

function page(s: ImporterSupport): string {
  const lines = [
    '---',
    `title: "Migrate from ${s.name}"`,
    `description: "Move your ${s.name} collections to TestPion: how to export, what comes over, what is changed and what does not."`,
    '---',
    '',
    NOTICE,
    '',
    '::: v-pre',
    '',
    `# Migrate from ${s.name}`,
    '',
    `Everything below is what TestPion's ${s.name} importer does today. An import never drops something silently: the Import dialog previews what will be created, and the compatibility report lists every item that came over with changes or not at all. See [Import fidelity](/getting-started/import-fidelity) for how the report reads.`,
    '',
    '## Export from ' + s.name,
    '',
    s.exportSteps.map((x, i) => `${i + 1}. ${x}`).join('\n'),
    '',
    '## Import into TestPion',
    '',
    s.give,
    '',
    `TestPion reads, by content (never by the file name):`,
    '',
    bullets(s.reads),
    '',
    'On the command line: `testpion import <file|folder|zip|link> -w <workspace>` (several files, a folder or a ZIP are previewed first; `--apply` imports them). **Home ▸ Migrate from…** opens the same dialog with these steps.',
    '',
    '## What comes over',
    '',
    bullets(s.maps),
    '',
    '## What is changed on the way',
    '',
    bullets(s.converted),
    '',
    '## What does not come over',
    '',
    bullets(s.notMapped),
  ];
  if (s.id === 'postman')
    lines.push('', "## Postman's words in TestPion", '', "Where to find what you know. In the command palette (Ctrl+K), typing the Postman word finds the row.", '', table(POSTMAN_WORDS.map((w): [string, string] => [w.theirs, `**${w.ours}**: ${w.where}`]), ['In Postman', 'In TestPion']));
  if (s.scripts) lines.push('', `## Scripts (${s.scripts.api})`, '', 'Scripts become TestPion\'s `tp.*`; anything the table does not list is left as written and still runs where the sandbox can run it.', '', scriptTable(s.scripts.table));
  if (s.templates) lines.push('', '## Variables and templates', '', s.templates);
  lines.push('', '## Importing again and going back', '', `Import the same source again and TestPion **updates** the collection it made instead of adding a copy, matching on ${s.updateKey}: the preview shows *replace*, *new* or *skip* for each item (an item you edited here is skipped unless you choose *replace*), and the update is one undo step.`);
  if (s.writeBack) lines.push('', s.writeBack);
  lines.push('', ':::', '');
  return lines.join('\n');
}

const MARK: Record<'yes' | 'partly' | 'no', string> = { yes: 'yes', partly: 'partly', no: 'no' };

function overview(): string {
  const head = ['Feature', ...IMPORTER_SUPPORT.map((s) => `[${s.name}](/migrate/${s.id})`)];
  const rows = MATRIX_FEATURES.map((f) => [f, ...IMPORTER_SUPPORT.map((s) => MARK[s.matrix[f]])]);
  return [
    '---',
    'title: "Migrate to TestPion"',
    'description: "Bring your collections from Postman, Insomnia, Bruno, Hoppscotch, Thunder Client, Yaak, HTTPie or Apidog: one guide per tool, and what each importer supports."',
    '---',
    '',
    NOTICE,
    '',
    '# Migrate to TestPion',
    '',
    'Drop the files (or a folder, a ZIP, a repository link) on the window, or open **Home ▸ Migrate from…**, pick your tool, and follow the steps: the Import dialog **previews** what will be created and the **compatibility report** says what came over fully, with changes, or not at all. Scripts are converted to TestPion\'s `tp.*`. A second import of the same source **updates** what it made. One page per tool:',
    '',
    IMPORTER_SUPPORT.map((s) => `- [${s.name}](/migrate/${s.id}): ${s.reads[0]}`).join('\n'),
    '',
    '## What each importer supports',
    '',
    `| ${head.join(' | ')} |`,
    `|${head.map(() => '---').join('|')}|`,
    rows.map((r) => `| ${r.join(' | ')} |`).join('\n'),
    '',
    'Other formats import too: OpenAPI and Swagger, AsyncAPI, WSDL, HAR, `.http` files, `.env` files, GraphQL schemas, Arazzo workflows, and a copied cURL, fetch, PowerShell or HTTPie command. See [Export and import](/getting-started/export-import) and [Import fidelity](/getting-started/import-fidelity).',
    '',
  ].join('\n');
}

/** All the generated pages. */
export function migrationPages(): MigratePage[] {
  return [{ path: 'migrate/index.md', markdown: overview() }, ...IMPORTER_SUPPORT.map((s) => ({ path: `migrate/${s.id}.md`, markdown: page(s) }))];
}
