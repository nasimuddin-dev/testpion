/**
 * A triage of a failed run (AI-2) in words: Markdown (the CLI's `--triage` section, `testpion ai triage`, the Markdown
 * report, a CI job summary) and the "Triage (AI)" section added to a run's JUnit, HTML and Markdown reports when CI asks
 * for it (`testpion test … --triage` with a model). It never changes a result or the exit code: the reports' counts stay
 * the run's own.
 */
import { existsSync, readFileSync } from 'node:fs';
import { atomicWrite } from '../storage/fsutil.js';
import type { ReportFormat } from './reports.js';
import type { TriageReport } from '../ai/triage.js';

const pct = (c: number | undefined) => (typeof c === 'number' ? ` · ${Math.round(c * 100)}% sure` : '');

/** The command that runs a triaged run's failed tests again: its collection's failed requests, or its failed tests. */
export const rerunCommand = (r: Pick<TriageReport, 'run' | 'runId'>): string =>
  r.run.origin?.kind === 'collection' ? `testpion run-collection ${r.run.origin.collectionId} --rerun-failed ${r.runId}` : `testpion test --rerun-failed ${r.runId}`;

/** The triage as Markdown: the causes with their evidence and proposed fixes, then the groups. */
export function triageMarkdown(r: TriageReport, o: { heading?: string } = {}): string {
  const items = new Map((r.proposal?.items ?? []).map((i) => [i.id, i]));
  const out = [
    `## ${o.heading ?? 'Triage'}${r.ai ? ' (AI)' : ''}`,
    '',
    `${r.failures} failure${r.failures === 1 ? '' : 's'} of run ${r.runId} (${r.run.name}) in ${r.groups.length} group${r.groups.length === 1 ? '' : 's'}${r.ai && r.model ? ` · causes by ${r.model}, review before applying` : ' · grouped by TestPion (no model)'}.`,
  ];
  if (r.fallback) out.push('', `_${r.fallback}_`);
  if (r.summary) out.push('', r.summary);
  for (const f of r.findings) {
    out.push(
      '',
      `### ${f.title}`,
      '',
      `**${f.kind}**${f.count !== undefined ? ` · ${f.count} failure${f.count === 1 ? '' : 's'}` : ''}${pct(f.confidence)}${f.groups?.length ? ` · groups ${f.groups.join(', ')}` : ''}`,
    );
    if (f.explanation) out.push('', f.explanation);
    for (const e of f.evidence.slice(0, 8)) out.push(`- ${e.text}`);
    const fixes = (r.proposal?.items ?? []).filter((i) => i.finding === f.id);
    for (const i of fixes) {
      const badge = i.verification.map((b) => `${b.status === 'pass' ? '✓' : b.status === 'fail' ? '✗' : b.status === 'warn' ? '!' : '–'} ${b.label}`).join('; ');
      out.push(`- **Proposed${i.kind === 'text' ? '' : ' fix'}:** ${i.title}${badge ? ` (${badge})` : ''}`);
    }
  }
  if (r.proposal && [...items.values()].some((i) => i.kind !== 'text'))
    out.push('', `Apply: \`testpion ai apply ${r.proposal.id}\` (the ticked items) · rerun the affected tests: \`${rerunCommand(r)}\``);
  if (r.omitted.groups) out.push('', `_${r.omitted.groups} more groups (${r.omitted.failures} failures) were not analysed._`);
  return `${out.join('\n')}\n`;
}

const xml = (s: string) => s.replace(/]]>/g, ']]]]><![CDATA[>');
const html = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/**
 * Add the "Triage (AI)" section to a run's reports (see the module comment): JUnit gets it as the suite's
 * `<system-out>`, HTML as a section before its footer, Markdown at its end. A report that is not there is skipped.
 */
export function appendTriageToReports(paths: Partial<Record<ReportFormat, string>>, r: TriageReport): string[] {
  const done: string[] = [];
  const text = triageMarkdown(r, { heading: 'Triage' });
  const edit = (p: string | undefined, fn: (s: string) => string | undefined) => {
    if (!p || !existsSync(p)) return;
    const next = fn(readFileSync(p, 'utf8'));
    if (next !== undefined) {
      atomicWrite(p, next);
      done.push(p);
    }
  };
  edit(paths.junit, (s) => {
    const at = s.lastIndexOf('  </testsuite>');
    return at < 0 ? undefined : `${s.slice(0, at)}    <system-out><![CDATA[${xml(text)}]]></system-out>\n${s.slice(at)}`;
  });
  edit(paths.html, (s) => {
    const at = s.lastIndexOf('<p class="muted">Generated by TestPion</p>');
    const section = `<section id="triage"><pre style="white-space:pre-wrap">${html(text)}</pre></section>\n`;
    return at < 0 ? undefined : `${s.slice(0, at)}${section}${s.slice(at)}`;
  });
  edit(paths.markdown, (s) => `${s.trimEnd()}\n\n${text}`);
  return done;
}
