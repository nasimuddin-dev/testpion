import { existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { liveKinds } from '@testpion/shared';
import { atomicWrite, realPathOf } from '../storage/fsutil.js';
import { SECRETS_ALLOW_FILE } from './secrets-allow.js';
import { repoRoot, toRepoPath } from './git.js';

/**
 * A starter CODEOWNERS (release C of planning/git-everything.md §3, "CODEOWNERS"): one line per kind folder of the workspace,
 * so a team can say who must review a change to the environments, the MCP servers or the AI providers once the repository
 * asks for code-owner review. The owners are left for the person to fill in: a line with a team that does not exist (or has
 * no members) protects nothing and fails without a word, so the lines are comments until `owner` is given.
 *
 * It never overwrites: a CODEOWNERS that exists in any of the places GitHub reads is left as it is. It is written only when the
 * workspace is the repository itself (the file belongs to the repository's root, outside a workspace in a subfolder).
 */
export interface CodeownersPlan {
  /** Where GitHub reads it from, relative to the repository root. */
  path: string;
  /** A CODEOWNERS exists already (at this path, relative to the repository root); nothing is written. */
  existing?: string;
  /** The workspace is a folder of the repository: the file is not in the workspace, so it is not written (the text is given). */
  insideRepository: boolean;
  text: string;
  lines: Array<{ pattern: string; what: string }>;
}

export const CODEOWNERS_PLACES = ['.github/CODEOWNERS', 'CODEOWNERS', 'docs/CODEOWNERS'];

/** What owners usually differ on, per kind folder or file: most specific wording first. */
const SPECIAL: Array<{ path: string; what: string }> = [
  { path: 'environments/', what: 'Environments (variables other people run against)' },
  { path: 'mcp-servers.json', what: 'MCP servers (commands and URLs agents connect to)' },
  { path: 'providers.json', what: 'AI providers (endpoints that receive prompts)' },
  { path: 'workspace.json', what: 'Workspace settings and variables' },
  { path: '.gitattributes', what: 'Merge and diff drivers, line endings, LFS' },
  { path: '.gitignore', what: 'What stays out of git' },
  { path: SECRETS_ALLOW_FILE, what: 'Values the secret scan lets through: review every change' },
];

/** The CODEOWNERS for the workspace at `ws`: lines for the kind folders it has. */
export async function planCodeowners(ws: string, o: { owner?: string } = {}): Promise<CodeownersPlan> {
  const real = realPathOf(ws);
  const repo = await repoRoot(ws);
  const base = repo ? toRepoPath(repo, ws, '.') : '.';
  const prefix = base && base !== '.' ? `/${base}/` : '/';
  const entries: Array<{ pattern: string; what: string }> = [];
  const seen = new Set<string>();
  const add = (path: string, what: string) => {
    if (seen.has(path)) return;
    const abs = join(real, path.replace(/\/$/, ''));
    if (!existsSync(abs)) return;
    seen.add(path);
    entries.push({ pattern: `${prefix}${path}`, what });
  };
  for (const s of SPECIAL) add(s.path, s.what);
  // every other stored kind: its folder (collections/, tests/, specs/, datasets/, library/ …) or its single file
  for (const k of liveKinds()) {
    const st = k.storage;
    if (st.layout === 'file-per-item' || st.layout === 'raw-document') add(`${st.dir}/`, k.plural);
    else if (st.layout === 'library') add('library/', 'Saved items (gRPC, WebSocket, prompts, load tests, evaluations, monitors)');
    else if (st.layout === 'single-file' || st.layout === 'items-in-file') add(st.file, k.plural);
  }
  const owner = o.owner?.trim();
  const width = Math.max(...entries.map((e) => e.pattern.length), 0) + 2;
  const line = (e: (typeof entries)[number]) => `${owner ? '' : '# '}${e.pattern.padEnd(width)}${owner ?? '@your-org/team'}`;
  const text = [
    '# Who must review changes to each part of the TestPion workspace.',
    '# Generated by TestPion (testpion git codeowners). It takes effect when the repository requires',
    '# "Review from Code Owners" in the branch protection or ruleset.',
    '# Replace @your-org/team with real users or teams that have write access, then remove the leading "# ".',
    '',
    ...entries.flatMap((e) => [`# ${e.what}`, line(e)]),
    '',
  ].join('\n');
  let existing: string | undefined;
  if (repo) existing = CODEOWNERS_PLACES.find((p) => existsSync(join(repo, p)));
  return { path: CODEOWNERS_PLACES[0]!, ...(existing ? { existing } : {}), insideRepository: !!repo && base !== '.' && base !== '', text, lines: entries };
}

export interface CodeownersResult extends CodeownersPlan {
  written: boolean;
  /** Said when nothing was written. */
  reason?: string;
}

/** Write the starter file, never over one that exists and never outside the workspace. */
export async function writeCodeowners(ws: string, o: { owner?: string; dryRun?: boolean } = {}): Promise<CodeownersResult> {
  const plan = await planCodeowners(ws, o);
  const repo = await repoRoot(ws);
  if (!repo) return { ...plan, written: false, reason: 'The workspace is not in a git repository yet' };
  if (plan.existing) return { ...plan, written: false, reason: `${plan.existing} exists: it is never overwritten (add the lines you want to it)` };
  if (plan.insideRepository) return { ...plan, written: false, reason: `The workspace is the folder ${toRepoPath(repo, ws, '.')} of the repository: CODEOWNERS belongs to the repository root, outside the workspace. Copy the lines into it.` };
  if (!plan.lines.length) return { ...plan, written: false, reason: 'The workspace has nothing to own yet' };
  if (o.dryRun) return { ...plan, written: false };
  const file = join(realPathOf(ws), plan.path);
  mkdirSync(dirname(file), { recursive: true });
  atomicWrite(file, plan.text);
  return { ...plan, written: true };
}
