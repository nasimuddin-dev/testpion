/** The shared claim passes a claim-level metric needs (each is one call; a pass shared with another metric is paid once). */
type Pass = 'answer-claims' | 'reference-claims' | 'answer-vs-reference' | 'reference-vs-answer' | 'answer-vs-contexts' | 'reference-vs-contexts' | 'chunk-relevance';
function passes(s: SampleShape, ps: Pass[]): MetricEstimate {
  const parts = ps.map((p) => {
    switch (p) {
      case 'answer-claims':
        return judgeEstimate(s, { prompt: 80, reads: ['answerTokens'], items: claimsOf });
      case 'reference-claims':
        return judgeEstimate(s, { prompt: 80, reads: ['referenceTokens'], items: refClaimsOf });
      case 'answer-vs-reference':
        return judgeEstimate(s, { prompt: 120, reads: ['answerTokens', 'referenceTokens'], items: claimsOf });
      case 'reference-vs-answer':
        return judgeEstimate(s, { prompt: 120, reads: ['answerTokens', 'referenceTokens'], items: refClaimsOf });
      case 'answer-vs-contexts':
        return judgeEstimate(s, { prompt: 120, reads: ['answerTokens', 'contextTokens'], items: claimsOf });
      case 'reference-vs-contexts':
        return judgeEstimate(s, { prompt: 120, reads: ['referenceTokens', 'contextTokens'], items: refClaimsOf });
      case 'chunk-relevance':
        return judgeEstimate(s, { prompt: 120, reads: ['referenceTokens', 'contextTokens'], items: (x) => x.contexts });
    }
  });
  return parts.reduce((a, b) => ({ llmCalls: a.llmCalls + b.llmCalls, embedCalls: 0, inputTokens: a.inputTokens + b.inputTokens, outputTokens: a.outputTokens + b.outputTokens }), { llmCalls: 0, embedCalls: 0, inputTokens: 0, outputTokens: 0 });
}

