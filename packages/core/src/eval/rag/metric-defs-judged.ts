const claim = (d: Omit<MetricDef, 'group' | 'kind' | 'judge' | 'version' | 'aliases' | 'sources' | 'check' | 'shares' | 'prompts' | 'calls'> & { passes: Pass[]; aliases?: string[]; ragas?: MetricDef['ragas'] }): MetricDef => {
  const { passes: ps, ...rest } = d;
  return {
    group: 'claims',
    kind: 'judged',
    judge: 'service',
    version: `${d.id}-v1`,
    aliases: [],
    sources: [SRC.ragchecker, SRC.ragas],
    check: d.id,
    prompts: ['claims-v1', 'claims-reference-v1', 'claims-vs-reference-v1', 'reference-claims-vs-answer-v1', 'faithfulness-claims-v1', 'reference-claims-in-contexts-v1', 'chunk-relevance-v1'],
    shares: 'claim-passes',
    calls: `${ps.length} (passes shared with the other claim-level metrics are paid once)`,
    ...rest,
    estimate: (s) => passes(s, ps),
  };
};

