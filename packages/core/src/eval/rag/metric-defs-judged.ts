const claimsOf = (s: SampleShape) => Math.max(1, Math.min(30, Math.round(s.answerTokens / 25)));
const refClaimsOf = (s: SampleShape) => Math.max(1, Math.min(30, Math.round(s.referenceTokens / 25)));

