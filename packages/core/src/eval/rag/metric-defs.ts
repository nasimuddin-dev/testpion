const tok = (s: string) => Math.ceil(s.length / 4);
/** The fixed part of every judge call: the task's instruction, the verdict format and the metric's own wording. */
const FIXED = tok(RAG_JUDGE_INSTRUCTION) + tok(JSON.stringify(VERDICT_SCHEMA)) + 60;

/** A judged metric's estimate: `calls` calls, each reading the given inputs and writing `items` verdicts. */
export function judgeEstimate(s: SampleShape, o: { calls?: number; prompt: number; reads: Array<keyof SampleShape>; items: (s: SampleShape) => number }): MetricEstimate {
  const calls = o.calls ?? 1;
  const input = FIXED + o.prompt + o.reads.reduce((a, k) => a + s[k], 0);
  return { llmCalls: calls, embedCalls: 0, inputTokens: calls * input, outputTokens: calls * (80 + 45 * o.items(s)) };
}
