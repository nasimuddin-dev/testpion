// Embeds Handlebars (MIT, handlebarsjs.com) into src/scripts/handlebars.generated.ts. A Visualizer template comes from
// a workspace script, so it is compiled and rendered inside the QuickJS sandbox (no process, require or files), never in
// the host. The host does not load the handlebars package at run time.
//
// Run: npm run handlebars -w @testpion/core   (after updating the handlebars dev dependency)
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

const pkg = require('handlebars/package.json');
const src = readFileSync(require.resolve('handlebars/dist/handlebars.min.js'), 'utf8');
const out = [`// Generated by scripts/make-handlebars.cjs from handlebars ${pkg.version} (MIT). Do not edit.`, `export const HANDLEBARS_VERSION = ${JSON.stringify(pkg.version)};`, `export const HANDLEBARS_SOURCE = ${JSON.stringify(src)};`, ''].join('\n');
writeFileSync(join(__dirname, '..', 'src', 'scripts', 'handlebars.generated.ts'), out);
console.log(`handlebars ${pkg.version}: ${src.length} bytes`);
