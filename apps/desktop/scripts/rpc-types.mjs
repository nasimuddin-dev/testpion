// Generates apps/desktop/src/lib/rpc-params.generated.ts from the parameter tables of the backend (backend/rpc-params.ts):
//   node scripts/rpc-types.mjs          writes the file
//   node scripts/rpc-types.mjs --check  fails when the file is out of date (tests/unit/rpc-contract.test.ts does the same)
// The tables are the contract of every RPC method's parameters (checked at run time before a handler runs); this turns the
// same table into types, so a window (or a hosted client) is checked at compile time against it, from one source.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = join(here, '..', 'backend', 'rpc-params.ts');
export const TARGET = join(here, '..', 'src', 'lib', 'rpc-params.generated.ts');

/** One table type ("s", "n?", "s|null", "wpa" …) as a TypeScript type; `optional` says whether the key gets a `?`. */
export function tsType(spec) {
  const optional = spec.endsWith('?');
  const parts = (optional ? spec.slice(0, -1) : spec).split('|');
  const one = (p) => {
    switch (p) {
      case 's':
      case 'string':
      case 'wp':
      case 'p':
      case 'pn':
        return 'string';
      case 'wpa':
      case 'sa':
        return 'string[]';
      case 'n':
      case 'number':
        return 'number';
      case 'b':
        return 'boolean';
      case 'o':
      case 'object':
        return 'Record<string, unknown>';
      case 'a':
        return 'unknown[]';
      case 'x':
        return 'unknown';
      case 'null':
        return 'null';
      default:
        throw new Error(`rpc-params.ts: unknown parameter type "${p}"`);
    }
  };
  return { optional, type: [...new Set(parts.map(one))].join(' | ') };
}

/** The tables of the source: { common: {key: spec}, methods: {method: {key: spec}} }. */
export function parseTables(source) {
  const text = source.replace(/\r\n/g, '\n');
  const pairs = (body) => Object.fromEntries([...body.matchAll(/(?:^|[,{\s])'?([A-Za-z_$][\w$]*)'?\s*:\s*'([^']*)'/g)].map((m) => [m[1], m[2]]));
  const common = /const COMMON: ParamSpec = \{([\s\S]*?)\n\};/.exec(text);
  const table = /export const RPC_PARAMS: Record<string, ParamSpec> = \{\n([\s\S]*?)\n\};/.exec(text);
  if (!common || !table) throw new Error('rpc-params.ts: the COMMON or RPC_PARAMS table was not found');
  const methods = {};
  for (const m of table[1].matchAll(/^\s*'([\w.]+)': \{(.*)\},?\s*$/gm)) methods[m[1]] = pairs(m[2]);
  return { common: pairs(common[1].replace(/\/\*\*[\s\S]*?\*\//g, '')), methods };
}

export function generate(source) {
  const { common, methods } = parseTables(source);
  const lines = [
    '// Generated by apps/desktop/scripts/rpc-types.mjs from backend/rpc-params.ts: do not edit (npm run rpc-types -w @testpion/desktop).',
    '// The parameters of every RPC method, as the backend checks them before the handler runs.',
    '',
    '/** Parameters that name something by its id or name, accepted by every method (the backend checks them wherever they appear). */',
    'export interface RpcCommonParams {',
    ...Object.keys(common).map((k) => `  ${k}${tsType(common[k]).optional ? '?' : ''}: ${tsType(common[k]).type};`),
    '}',
    '',
    'export interface RpcParamTypes {',
  ];
  for (const name of Object.keys(methods).sort()) {
    const spec = methods[name];
    const keys = Object.keys(spec).filter((k) => !(k in common) || spec[k] !== common[k]);
    const body = keys.map((k) => {
      const t = tsType(spec[k]);
      return `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}${t.optional ? '?' : ''}: ${t.type}`;
    });
    lines.push(`  '${name}': RpcCommonParams${body.length ? ` & { ${body.join('; ')} }` : ''};`);
  }
  lines.push('}', '', `export const RPC_METHOD_COUNT = ${Object.keys(methods).length};`, '');
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = generate(readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    if (readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n') !== text) {
      console.error('apps/desktop/src/lib/rpc-params.generated.ts is out of date: run npm run rpc-types -w @testpion/desktop');
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, text);
    console.log(`wrote ${TARGET}`);
  }
}
