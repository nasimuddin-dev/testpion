/** The icon of an item kind (its registry icon): the same one wherever the kind is named by a row. */
export function KindIcon({ kind, size = 14, className }: { kind: KindId; size?: number; className?: string }) {
  const Icon = KIND_ICONS[KIND_INFO[kind].icon] ?? FileDiff;
  return <Icon size={size} className={className} aria-hidden />;
}
