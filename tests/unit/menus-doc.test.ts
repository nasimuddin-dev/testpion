import { describe, expect, it } from 'vitest';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { nodeMenuTable } from '../../apps/desktop/src/lib/node-menu-doc';

/**
 * The docs' per-kind menu table (docs/getting-started/finding-your-way.md, "Menus") is generated from the function that
 * builds the menus. After a menu change: `UPDATE_DOCS=1 npx vitest run tests/unit/menus-doc.test.ts` writes it.
 */
const FILE = join(__dirname, '../../docs/getting-started/finding-your-way.md');
const START = '<!-- node-menus:start (generated by tests/unit/menus-doc.test.ts) -->';
const END = '<!-- node-menus:end -->';

describe('the docs list every node menu as the app builds it', () => {
  it('the table in finding-your-way.md is in sync', () => {
    const doc = readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n');
    const a = doc.indexOf(START);
    const b = doc.indexOf(END);
    expect(a, 'the page needs the generated block').toBeGreaterThan(0);
    const table = nodeMenuTable();
    const current = doc.slice(a + START.length, b).trim();
    if (process.env.UPDATE_DOCS && current !== table) writeFileSync(FILE, `${doc.slice(0, a + START.length)}\n\n${table}\n\n${doc.slice(b)}`);
    else expect(current).toBe(table);
  });
});
