import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createTestPionMcpServer, EnvSecretStore, WorkspaceManager, type WorkspaceStore } from '../../packages/core/src/index.js';
import { ITEM_KINDS } from '../../packages/shared/src/item-ref.js';
import { buildProgram } from '../../packages/cli/src/index.js';
import { LEGACY } from '../../packages/cli/src/groups.js';

/**
 * docs/public/llms.txt is what an agent reads first. Its "Start here" block is written by hand; the block between the
 * markers is generated from the registries (the item kinds, the MCP tools, the CLI commands), so a new kind, tool or
 * command appears there by itself. After a change: `UPDATE_DOCS=1 npx vitest run tests/unit/llms-txt.test.ts`.
 */
const FILE = join(__dirname, '../../docs/public/llms.txt');
const START = '<!-- registries:start (generated by tests/unit/llms-txt.test.ts) -->';
const END = '<!-- registries:end -->';

const dir = mkdtempSync(join(tmpdir(), 'tp-llms-'));
let store: WorkspaceStore;
let client: Client;
let tools: string[] = [];

beforeAll(async () => {
  const ws = join(dir, 'ws');
  cpSync(join(process.cwd(), 'examples', 'veterinary-workspace'), ws, { recursive: true, filter: (p) => !/database\.sqlite|[\\/](runs|traces|payloads)([\\/]|$)/.test(p) });
  const mgr = new WorkspaceManager(join(dir, 'home'));
  store = mgr.open(ws);
  const server = createTestPionMcpServer({ store, secrets: new EnvSecretStore(), settings: mgr.loadSettings() });
  const [a, b] = InMemoryTransport.createLinkedPair();
  client = new Client({ name: 'test', version: '1' });
  await Promise.all([server.connect(a), client.connect(b)]);
  tools = (await client.listTools()).tools.map((t) => t.name).sort();
}, 60_000);
afterAll(async () => {
  await client.close();
  store.close();
  rmSync(dir, { recursive: true, force: true, maxRetries: 3 });
});

const commands = () =>
  buildProgram()
    .commands.map((c) => c.name())
    .filter((n) => n !== 'help')
    .sort();

function block(): string {
  return [
    `Item kinds (${ITEM_KINDS.length}; \`testpion kinds --json\` says what each can do): ${[...ITEM_KINDS].sort().join(', ')}.`,
    '',
    `MCP tools (${tools.length}; \`search_tools\` finds one by what you want to do): ${tools.join(', ')}.`,
    '',
    `CLI commands (${commands().length} top-level words; groups such as \`git\`, \`rag\`, \`lint\`, \`mock\` and \`openapi\` have subcommands; the old hyphenated spellings ${Object.keys(LEGACY).join(', ')} still work): ${commands().join(', ')}.`,
  ].join('\n');
}

describe('llms.txt', () => {
  it('starts with what an agent should do first', () => {
    const text = readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n');
    const start = text.slice(text.indexOf('## Start here'), text.indexOf('Key facts for agents'));
    expect(start, 'a "## Start here" section before the key facts').not.toBe('');
    for (const word of ['testpion kinds', 'search_tools', 'testpion_guide', 'what_needs_attention', '--dry-run', '--yes', 'confirm']) expect(start).toContain(word);
  });

  it('the registry block lists every kind, MCP tool and CLI command', () => {
    const text = readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n');
    const a = text.indexOf(START);
    const b = text.indexOf(END);
    expect(a, 'llms.txt needs the generated block').toBeGreaterThan(0);
    const current = text.slice(a + START.length, b).trim();
    const generated = block();
    if (process.env.UPDATE_DOCS && current !== generated) writeFileSync(FILE, `${text.slice(0, a + START.length)}\n\n${generated}\n\n${text.slice(b)}`);
    else expect(current).toBe(generated);
    for (const k of ITEM_KINDS) expect(text).toContain(k);
    for (const t of tools) expect(text).toContain(t);
    for (const c of commands()) expect(text).toContain(c);
  });

  it('is organised: several sections, and no number that is out of date', () => {
    const text = readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n');
    expect((text.match(/^## /gm) ?? []).length).toBeGreaterThanOrEqual(8);
    expect(text).not.toMatch(/More than 120 tools/);
  });
});
