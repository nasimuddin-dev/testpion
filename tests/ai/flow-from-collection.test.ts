/**
 * AI-1 · Integration flow from a collection or folder: golden cases with the mock provider (scripted answers). The
 * draft, the context (folder scope, privacy, secrets), the plan → flow build (requests by id, invented ones dropped),
 * the verifiers and the repair loop (invalid JSON, a cycle, a value used before it is extracted), apply and undo, and
 * the draft without AI.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import {
  applyProposal,
  buildFlowFile,
  cleanStepName,
  createEngineContext,
  draftFlowProposal,
  flowOrderProblems,
  flowSourceRef,
  flowVariableProblems,
  STEP_NAME_MAX,
  MemorySecretStore,
  pointFlowAtMock,
  prepareFlowContext,
  runAiTask,
  sameEndpoint,
  undoProposal,
  verifyFlowOnMock,
} from '../../packages/core/src/index.js';
import { harness, LIVE, printScorecard, score } from './harness.js';
import { SECRET, SHOP } from './fixtures.js';

afterAll(printScorecard);

const GOOD = {
  name: 'Order lifecycle',
  summary: 'Creates an order, reads it back, deletes it, and checks a missing order answers 404.',
  assumptions: ['POST /orders answers with the new id in $.id'],
  steps: [
    {
      id: 'create-order',
      request: 'req-create',
      extract: { orderId: '$.id' },
      assertions: [
        { type: 'status', expected: 201 },
        { type: 'exists', path: '$.id' },
      ],
    },
    { id: 'read-order', request: 'req-get', dependsOn: ['create-order'], url: 'https://evil.example.net/orders/{{orderId}}', assertions: [{ type: 'status', expected: 200 }] },
    { id: 'delete-order', request: 'req-delete', dependsOn: ['read-order'], url: '{{baseUrl}}/orders/{{orderId}}', assertions: [{ type: 'status', expected: 204 }] },
    { id: 'missing-order', request: 'req-get', url: '{{baseUrl}}/orders/does-not-exist', negative: true, assertions: [{ type: 'status', expected: 404 }] },
  ],
};
const json = (v: unknown) => JSON.stringify(v);

const shop = (secrets?: Record<string, string>, rules?: Parameters<typeof harness>[0]['rules']) => {
  const h = harness({ rules, secrets });
  h.store.saveCollection(structuredClone(SHOP));
  return h;
};
const ORDERS = { kind: 'folder' as const, collectionId: 'shop', folderId: 'fld-orders' };

describe('the flow source and its draft (no AI)', () => {
  it('finds a folder by name or path, and its requests only', () => {
    const h = shop();
    try {
      expect(flowSourceRef(h.store, { collection: 'Shop', folder: 'Orders' })).toEqual(ORDERS);
      expect(flowSourceRef(h.store, { collection: 'shop' })).toEqual({ kind: 'collection', collectionId: 'shop' });
      expect(() => flowSourceRef(h.store, { collection: 'Shop', folder: 'Refunds' })).toThrow(/No folder "Refunds"/);
      const p = prepareFlowContext(h.store, ORDERS);
      const ids = (p.context.requests as Array<{ id: string }>).map((r) => r.id);
      expect(ids).toEqual(['req-create', 'req-get', 'req-delete']);
      expect(p.label).toBe('Shop / Orders');
      expect(p.path).toBe('flows/shop-orders.yaml');
      // header names, never values; the auth type, never the token
      expect((p.context.requests as Array<Record<string, unknown>>)[0]).toMatchObject({ headers: ['X-Api-Key'], auth: 'bearer' });
      // the deterministic draft: the CRUD life of an order, by request id
      const draft = (p.context.draft as { steps: Array<{ request: string }> }).steps.map((s) => s.request);
      expect(draft).toContain('req-create');
      expect(draft).toContain('req-delete');
    } finally {
      h.cleanup();
    }
  });

  it('same endpoint: values may differ, literal segments and their number may not', () => {
    expect(sameEndpoint('{{baseUrl}}/orders/ord-1', 'https://x/orders/{{orderId}}')).toBe(true);
    expect(sameEndpoint('{{baseUrl}}/orders/ord-1', '{{baseUrl}}/orders/does-not-exist')).toBe(true);
    expect(sameEndpoint('{{baseUrl}}/orders/ord-1', '{{baseUrl}}/users/{{id}}')).toBe(false);
    expect(sameEndpoint('{{baseUrl}}/orders', '{{baseUrl}}/orders/1/items')).toBe(false);
  });

  it('without a model, the draft is the proposal (labelled, verified, applicable)', async () => {
    const h = shop();
    try {
      const p = await draftFlowProposal(h.store, ORDERS, { surface: 'cli' });
      expect(p.model).toMatch(/no AI/);
      expect(p.notes![0]).toMatch(/No AI model is set up/);
      const item = p.items[0]!;
      expect(item.after).toMatch(/^# Generated by TestPion without AI/);
      expect(item.verification.find((b) => b.verifier === 'test-file')?.status).not.toBe('fail');
      expect(applyProposal(h.store, p.id).applied[0]!.path).toBe('flows/shop-orders.yaml');
    } finally {
      h.cleanup();
    }
  });

  it('a visualizer template in a request script is not a variable: the Patients draft passes every verifier and applies', async () => {
    // the example workspace's collection (read-only: read here, saved into the test's own temp workspace)
    const vet = JSON.parse(readFileSync(join(__dirname, '../../examples/veterinary-workspace/collections/veterinary-api.json'), 'utf8'));
    expect(vet.items[1].items[0].testScript).toContain('{{#each items}}');
    const h = harness({});
    try {
      h.store.saveCollection(vet);
      const ref = flowSourceRef(h.store, { collection: 'Veterinary API', folder: 'Patients' });
      const p = await draftFlowProposal(h.store, ref, { surface: 'cli' });
      const item = p.items[0]!;
      expect(item.after).toContain('{{#each items}}'); // the script is kept, and not read as variables
      expect(item.verification.filter((b) => b.status === 'fail')).toEqual([]);
      expect(item.verification.find((b) => b.verifier === 'flow-vars')?.status).toBe('pass');
      expect(applyProposal(h.store, p.id).applied[0]!.path).toBe(item.path);
      expect(h.store.readTestFile(item.path!)).toContain('{{#each items}}');
    } finally {
      h.cleanup();
    }
  });

  it('flow variables: blocks, scripts and descriptions are not uses; script-set and set-step names are defined', () => {
    const flow = [
      'tests:',
      '  - id: a',
      '    description: "shows {{notAVar}}"',
      '    url: "{{baseUrl}}/x/{{missing}}"',
      '    testScript: "tp.environment.set(\'token\', 1); const t = `{{total}} {{#each items}}{{id}}{{/each}}`"',
      '  - id: s',
      '    type: set',
      '    set: { other: 1 }',
      '  - id: b',
      '    url: "{{baseUrl}}/{{token}}/{{other}}/{{$guid}}"',
    ].join('\n');
    expect(flowVariableProblems(flow)).toEqual(['{{missing}} is used but no step extracts it and no variable has that name']);
    expect(flowOrderProblems('tests:\n  - id: a\n    extract: { total: $.n }\n  - id: b\n    testScript: "const t = `{{total}}`"\n')).toEqual([]);
  });

  it('step names: the plan may name a step (cleaned, at most 60 characters); an error case says so; names are unique', () => {
    const h = shop();
    try {
      const local = prepareFlowContext(h.store, ORDERS).local as Parameters<typeof buildFlowFile>[1];
      const built = buildFlowFile(
        {
          steps: [
            { id: 'a', request: 'req-get' },
            { id: 'b', request: 'req-get', negative: true },
            { id: 'c', request: 'req-get', negative: true },
            { id: 'd', request: 'req-create', name: `  Make\nan order ${'x'.repeat(80)}` },
            { id: 'e', request: 'req-delete', name: 'get order' },
          ],
        },
        local,
        { by: 'test', ai: true },
      );
      const names = [...built.yaml.matchAll(/^ {4}name: (.*)$/gm)].map((m) => m[1]!.replace(/^"|"$/g, ''));
      const get = (local.requests['req-get']!.node as { name: string }).name;
      expect(names[0]).toBe(get);
      expect(names[1]).toBe(`${get} — error case`);
      expect(names[2]).toBe(`${get} — error case (2)`);
      expect(names[3]).toMatch(/^Make an order x+…$/);
      expect(names[3]!.length).toBe(STEP_NAME_MAX);
      expect(cleanStepName(' \u0000 ')).toBeUndefined();
      expect(new Set(names.map((n) => n.toLowerCase())).size).toBe(names.length);
    } finally {
      h.cleanup();
    }
  });

  it('a value used by a step that does not wait for the step that extracts it is a problem', () => {
    expect(flowOrderProblems('tests:\n  - id: a\n    extract: { x: $.id }\n  - id: b\n    url: "{{baseUrl}}/{{x}}"\n')).toEqual([
      'step "b" uses {{x}} but does not wait for "a", which extracts it: add "a" to its dependsOn',
    ]);
    expect(flowOrderProblems('tests:\n  - id: a\n    extract: { x: $.id }\n  - id: m\n    dependsOn: [a]\n  - id: b\n    dependsOn: [m]\n    url: "{{baseUrl}}/{{x}}"\n')).toEqual([]);
  });
});

describe('flow-from-collection (mock provider unless AI_EVAL_LIVE=1)', () => {
  it('a good flow: steps from the saved requests by id, the host kept, auth inherited, checks verified', async () => {
    const h = shop({}, [{ match: '"source"', response: json(GOOD) }]);
    try {
      const r = await runAiTask(h.deps, { task: 'flow-from-collection', item: ORDERS });
      const p = r.proposal!;
      // live: a flow of the folder's requests that parses and whose variables hold
      const item0 = p?.items[0];
      score('flow-from-collection', 'shop orders folder', r, !!item0 && item0.verification.every((b) => b.status !== 'fail'));
      expect(p).toBeDefined();
      if (LIVE) return;
      expect(r.repairs).toBe(0);
      expect(p.title).toBe('Integration flow: Shop / Orders');
      expect(p.assumptions).toEqual(['POST /orders answers with the new id in $.id']);
      expect(p.summary).toMatch(/Creates an order/);
      const item = p.items[0]!;
      expect(item).toMatchObject({ kind: 'flow', path: 'flows/shop-orders.yaml', selected: true });
      expect(item.verification.map((b) => [b.verifier, b.status])).toEqual([
        ['test-file', 'pass'],
        ['flow-vars', 'pass'],
      ]);
      expect(item.after).toMatch(/^# AI-generated by TestPion \(Mock AI\/mock-model\) from Shop \/ Orders/);
      // the invented host is not used: the saved request's host with the extracted id
      expect(item.after).not.toContain('evil.example.net');
      expect(item.after).toContain('url: "{{baseUrl}}/orders/{{orderId}}"');
      expect(item.after).toContain('token: "{{token}}"');
      expect(p.notes ?? []).toEqual([]);
      expect(item.after).not.toMatch(/missing-order[\s\S]*extract:/);
      // nothing written until applied
      expect(() => h.store.readTestFile('flows/shop-orders.yaml')).toThrow();
      applyProposal(h.store, p.id);
      expect(h.store.readTestFile('flows/shop-orders.yaml')).toContain('create-order');
      undoProposal(h.store, p.id);
      expect(() => h.store.readTestFile('flows/shop-orders.yaml')).toThrow();
    } finally {
      h.cleanup();
    }
  });

  it('an answer that is not JSON is sent back and repaired', async () => {
    if (LIVE) return;
    const h = shop({}, [{ match: '.', responses: ['name: Orders\ntests:\n  - id: create-order\n    request: req-create', json(GOOD)] }]);
    try {
      const r = await runAiTask(h.deps, { task: 'flow-from-collection', item: ORDERS });
      expect(r.repairs).toBe(1);
      expect(r.problems).toEqual([]);
      expect(r.proposal!.items[0]!.selected).toBe(true);
    } finally {
      h.cleanup();
    }
  });

  it('a step naming a request that does not exist (or is outside the folder) is dropped and said so', async () => {
    if (LIVE) return;
    const answer = { ...GOOD, steps: [...GOOD.steps, { id: 'refund', request: 'req-refund-invented' }, { id: 'users', request: 'req-users' }] };
    const h = shop({}, [{ match: '.', response: json(answer) }]);
    try {
      const r = await runAiTask(h.deps, { task: 'flow-from-collection', item: ORDERS });
      const item = r.proposal!.items[0]!;
      expect(item.after).not.toContain('refund');
      expect(item.after).not.toContain('/users');
      expect(r.proposal!.notes!.filter((n) => n.startsWith('Dropped step'))).toHaveLength(2);
      expect(r.proposal!.notes![0]).toMatch(/req-refund-invented", which is not in Shop \/ Orders/);
    } finally {
      h.cleanup();
    }
  });

  it('a cycle (lint error) and a value used before it is extracted are repaired', async () => {
    if (LIVE) return;
    const cyclic = { ...GOOD, steps: GOOD.steps.map((s) => (s.id === 'create-order' ? { ...s, dependsOn: ['delete-order'] } : s)) };
    const unordered = { ...GOOD, steps: GOOD.steps.map((s) => (s.id === 'read-order' ? { ...s, dependsOn: [] } : s)) };
    const h = shop({}, [{ match: '.', responses: [json(cyclic), json(unordered), json(GOOD)] }]);
    try {
      const r = await runAiTask(h.deps, { task: 'flow-from-collection', item: ORDERS });
      expect(r.repairs).toBe(2);
      expect(r.problems).toEqual([]);
      expect(h.rec.requests[1]!.messages.at(-1)!.content).toMatch(/cycle|circular|depend/i);
      expect(h.rec.requests[2]!.messages.at(-1)!.content).toMatch(/does not wait for "create-order"/);
    } finally {
      h.cleanup();
    }
  });

  it('privacy: metadata only sends no body values; secrets are never sent; a folder sends only its requests', async () => {
    const h = shop({ apiKey: SECRET }, [{ match: '.', response: json(GOOD) }]);
    try {
      await runAiTask(h.deps, { task: 'flow-from-collection', item: ORDERS, privacy: 'metadata' });
      const sent = h.rec.sent();
      expect(sent).not.toContain('bookshelf');
      expect(sent).toContain('"item"');
      expect(sent).not.toContain(SECRET);
      expect(sent).not.toContain('req-users');
      expect(sent).not.toContain('List users');
      h.rec.requests.length = 0;
      await runAiTask(h.deps, { task: 'flow-from-collection', item: ORDERS });
      const full = h.rec.sent();
      expect(full).toContain('bookshelf');
      expect(full).not.toContain(SECRET);
    } finally {
      h.cleanup();
    }
  });

  it('a dry run shows what would be sent and the estimate, and sends nothing', async () => {
    const h = shop();
    try {
      const r = await runAiTask(h.deps, { task: 'flow-from-collection', item: ORDERS, dryRun: true });
      expect(r.dryRun).toBe(true);
      expect(h.rec.requests).toHaveLength(0);
      expect(r.preview.context.sections.map((s) => s.name)).toEqual(expect.arrayContaining(['source', 'requests', 'draft']));
      expect(r.preview.estimate.inputTokens).toBeGreaterThan(100);
      await expect(runAiTask(h.deps, { task: 'flow-from-collection' })).rejects.toThrow(/works on a workspace item/);
    } finally {
      h.cleanup();
    }
  });
});

describe('trying a flow on a mock never reaches a real server', () => {
  it('points every step at the mock, drops auth, and refuses steps a mock cannot serve', () => {
    const r = pointFlowAtMock(
      'defaults: { auth: { type: oauth2 } }\ntests:\n  - id: a\n    type: http\n    request: { method: GET, url: "https://api.example.com/orders?x=1", auth: { type: bearer, token: t } }\n  - id: b\n    url: "{{host}}/y"\n',
      'http://127.0.0.1:5555',
    );
    expect(r.blocked).toEqual([]);
    expect(r.text).toContain('http://127.0.0.1:5555/orders?x=1');
    expect(r.text).toContain('http://127.0.0.1:5555/y');
    expect(r.text).not.toMatch(/auth|oauth2|example\.com/);
    expect(pointFlowAtMock('tests:\n  - id: g\n    type: grpc\n    target: x:1\n', 'http://m').blocked).toEqual(['g (grpc)']);
  });

  it('runs the generated flow against the collection mock', async () => {
    const h = shop({}, [{ match: '.', response: json(GOOD) }]);
    const ctx = createEngineContext({ store: h.store, secrets: new MemorySecretStore(), settings: { pricing: [] } as never });
    try {
      const r = await runAiTask(h.deps, { task: 'flow-from-collection', item: ORDERS });
      const badge = await verifyFlowOnMock(r.proposal!.items[0]!.after, structuredClone(SHOP), ctx.services);
      expect(badge.verifier).toBe('flow-mock');
      expect(badge.label).toMatch(/steps pass on a mock of Shop/);
    } finally {
      await ctx.dispose();
      h.cleanup();
    }
  });
});
